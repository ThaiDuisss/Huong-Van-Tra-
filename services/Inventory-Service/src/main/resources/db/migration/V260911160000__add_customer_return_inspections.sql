CREATE TABLE customer_return_inspections (
    id BINARY(16) NOT NULL,
    is_deleted BIT(1) NOT NULL DEFAULT b'0',
    created_by BINARY(16) NULL,
    updated_by BINARY(16) NULL,
    created_at DATETIME(6) NULL,
    updated_at DATETIME(6) NULL,
    version BIGINT NULL,
    inspection_code VARCHAR(100) NOT NULL,
    return_id BINARY(16) NOT NULL,
    return_code VARCHAR(50) NOT NULL,
    branch_id BINARY(16) NOT NULL,
    order_id BINARY(16) NULL,
    order_code VARCHAR(50) NULL,
    status VARCHAR(50) NOT NULL,
    posted_at DATETIME(6) NULL,
    note VARCHAR(500) NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_customer_return_inspection_code UNIQUE (inspection_code),
    KEY idx_customer_return_inspections_return (return_id),
    KEY idx_customer_return_inspections_status (status),
    KEY idx_customer_return_inspections_created_at (created_at)
);

CREATE TABLE customer_return_inspection_lines (
    id BINARY(16) NOT NULL,
    is_deleted BIT(1) NOT NULL DEFAULT b'0',
    created_by BINARY(16) NULL,
    updated_by BINARY(16) NULL,
    created_at DATETIME(6) NULL,
    updated_at DATETIME(6) NULL,
    version BIGINT NULL,
    inspection_id BINARY(16) NOT NULL,
    return_item_id BINARY(16) NOT NULL,
    order_item_id BINARY(16) NULL,
    product_variant_id BINARY(16) NOT NULL,
    inventory_item_id BINARY(16) NOT NULL,
    quantity DECIMAL(18,2) NOT NULL,
    result VARCHAR(50) NOT NULL,
    destination_location_id BINARY(16) NULL,
    note VARCHAR(500) NULL,
    posted BIT(1) NOT NULL DEFAULT b'0',
    transaction_id BINARY(16) NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_customer_return_inspection_lines_inspection
        FOREIGN KEY (inspection_id) REFERENCES customer_return_inspections(id),
    KEY idx_customer_return_inspection_lines_inspection (inspection_id),
    KEY idx_customer_return_inspection_lines_return_item (return_item_id),
    KEY idx_customer_return_inspection_lines_product_variant (product_variant_id),
    KEY idx_customer_return_inspection_lines_status (posted),
    KEY idx_customer_return_inspection_lines_created_at (created_at)
);
